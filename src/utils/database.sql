CREATE TABLE Doctor (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(30) NOT NULL,
    prenom VARCHAR(30) NOT NULL,
    cnie VARCHAR(15) NOT NULL UNIQUE,
    specialite VARCHAR(50) NOT NULL,
    nom_cabinet VARCHAR(50) NOT NULL,
    telephone VARCHAR(15),
    adresse_cabinet VARCHAR(255),
    mot_de_passe VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE Patient (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(30) NOT NULL,
    prenom VARCHAR(30) NOT NULL,
    cnie VARCHAR(15) NOT NULL UNIQUE,
    mot_de_passe VARCHAR(255) NOT NULL,
    date_naissance DATE,
    ville VARCHAR(30),
    telephone VARCHAR(15),
    adresse VARCHAR(255),
    sexe VARCHAR(1) CHECK (sexe IN ('F', 'M')),
    compte_cree BOOLEAN DEFAULT TRUE,
    email VARCHAR(40),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE Doctor_Patient (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_doctor INTEGER NOT NULL,
    nom VARCHAR(30) NOT NULL,
    prenom VARCHAR(30) NOT NULL,
    cnie VARCHAR(15) NOT NULL,
    date_naissance DATE,
    ville VARCHAR(30),
    telephone VARCHAR(15),
    adresse VARCHAR(255),
    sexe VARCHAR(1) CHECK (sexe IN ('F', 'M')),
    remarque TEXT,
    date_creation TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (id_doctor, cnie),
    FOREIGN KEY (id_doctor) REFERENCES Doctor(id) ON DELETE CASCADE
);

CREATE TABLE Rendez_vous (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_doctor INTEGER NOT NULL,
    cnie_patient VARCHAR(15) NOT NULL,
    date_rendez_vous DATE NOT NULL,
    heure TIME,
    raison VARCHAR(255),
    statut VARCHAR(20) DEFAULT 'upcoming'
        CHECK (statut IN ('upcoming', 'present', 'absent')),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (id_doctor) REFERENCES Doctor(id) ON DELETE CASCADE,
    UNIQUE (date_rendez_vous, cnie_patient, heure)
);

CREATE TABLE Medicament (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_doctor INTEGER NOT NULL,
    cnie_patient VARCHAR(15) NOT NULL,
    nom VARCHAR(100) NOT NULL,
    date_debut DATE NOT NULL,
    periode INTEGER,
    description TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (id_doctor) REFERENCES Doctor(id) ON DELETE CASCADE,
    UNIQUE (cnie_patient, nom, date_debut, id_doctor)
);

CREATE TABLE Test_Medical (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_doctor INTEGER NOT NULL,
    cnie_patient VARCHAR(15) NOT NULL,
    type_test VARCHAR(100) NOT NULL,
    resultat TEXT,
    date_test DATE NOT NULL,
    type_doctor VARCHAR(20) NOT NULL CHECK (type_doctor IN ('interne', 'externe')),
    statut VARCHAR(20) DEFAULT 'en attente'
        CHECK (statut IN ('pending', 'completed')),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (id_doctor) REFERENCES Doctor(id) ON DELETE CASCADE
);
