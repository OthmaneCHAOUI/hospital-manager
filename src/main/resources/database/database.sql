CREATE TABLE Doctor (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(30) NOT NULL,
    firstName VARCHAR(30) NOT NULL,
    nationalId VARCHAR(15) NOT NULL UNIQUE,
    specialty VARCHAR(50) NOT NULL,
    clinic_name VARCHAR(50) NOT NULL,
    phone VARCHAR(15),
    clinic_address VARCHAR(255),
    password VARCHAR(255) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE Patient (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(30) NOT NULL,
    firstName VARCHAR(30) NOT NULL,
    nationalId VARCHAR(15) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    birth_date DATE,
    city VARCHAR(30),
    phone VARCHAR(15),
    address VARCHAR(255),
    gender VARCHAR(1) CHECK (gender IN ('F', 'M')),
    account_created BOOLEAN DEFAULT TRUE,
    email VARCHAR(40),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE DoctorPatient (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_doctor INTEGER NOT NULL,
    name VARCHAR(30) NOT NULL,
    firstName VARCHAR(30) NOT NULL,
    nationalId VARCHAR(15) NOT NULL,
    birth_date DATE,
    city VARCHAR(30),
    phone VARCHAR(15),
    address VARCHAR(255),
    gender VARCHAR(1) CHECK (gender IN ('F', 'M')),
    note TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (id_doctor, nationalId),
    FOREIGN KEY (id_doctor) REFERENCES Doctor(id) ON DELETE CASCADE
);

CREATE TABLE Appointment (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_doctor INTEGER NOT NULL,
    patient_national_id VARCHAR(15) NOT NULL,
    appointment_date DATE NOT NULL,
    time TIME,
    reason VARCHAR(255),
    status VARCHAR(20) DEFAULT 'upcoming'
        CHECK (status IN ('upcoming', 'present', 'absent')),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (id_doctor) REFERENCES Doctor(id) ON DELETE CASCADE,
    UNIQUE (appointment_date, patient_national_id, time)
);

CREATE TABLE Medication (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_doctor INTEGER NOT NULL,
    patient_national_id VARCHAR(15) NOT NULL,
    name VARCHAR(100) NOT NULL,
    start_date DATE NOT NULL,
    duration INTEGER,
    description TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (id_doctor) REFERENCES Doctor(id) ON DELETE CASCADE,
    UNIQUE (patient_national_id, name, start_date, id_doctor)
);

CREATE TABLE MedicalTest (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_doctor INTEGER NOT NULL,
    patient_national_id VARCHAR(15) NOT NULL,
    test_type VARCHAR(100) NOT NULL,
    result TEXT,
    test_date DATE NOT NULL,
    doctor_type VARCHAR(20) NOT NULL CHECK (doctor_type IN ('internal', 'external')),
    status VARCHAR(20) DEFAULT 'pending'
        CHECK (status IN ('pending', 'completed')),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (id_doctor) REFERENCES Doctor(id) ON DELETE CASCADE
);
